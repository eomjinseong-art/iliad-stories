export function heroBySlug(slug: string) {
  return heroes.find((hero) => hero.slug === slug);
}

export function heroesByCamp(camp: Camp) {
  return heroes.filter((hero) => hero.camp === camp);
}

const REQUIRED_SLUGS = ["achilles", "hector", "agamemnon", "patroclus", "helen", "paris", "priam", "odysseus", "aeneas"] as const;
for (const slug of REQUIRED_SLUGS) {
  if (!heroBySlug(slug)) throw new Error(`필수 인물 경로가 없습니다: /heroes/${slug}`);
}
